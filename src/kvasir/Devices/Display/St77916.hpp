/// Sitronix ST77916 and ST77922, as DcsPanel chip policies.
///
/// **Not yet tested on hardware.** From the datasheets (ST77916_SPEC_V1.0.md,
/// ST77922_SPEC_V0.1.md) and Espressif's esp_lcd_st77916 / esp_lcd_st77922 init tables.
/// The bus framing is the CO5300's. Datasheets (both chips, 8.8.5 and 7.4.5):
/// - command write 02h + {00h, CMD, 00h} single-lane; pixels 32h + {00h, 2Ch, 00h} then
///   four lanes, SDA3 carrying the nibble MSB: plain big-endian RGB565 on the wire
/// - register read 0Bh + address, then **8 dummy clocks**, then the data on SDA0
/// - TSCYCW 16 ns (62.5 MHz) but the pin table caps SCL at 50 MHz; TSCYCR 150 ns
///   (6.67 MHz) for reads
/// - RESX: >= 9 us low; 5 ms before the first command; SLPOUT not within 120 ms of
///   reset, and 120 ms after SLPOUT before SLPIN (ST77916 7.4.6 notes, SLPOUT restriction)
/// - CASET/RASET are 16 bit fields with no alignment requirement stated
///
/// The vendor tables set gamma, power and GIP timing for one panel; another module needs its
/// supplier's (a wrong table gives a dim or mirrored picture, not a dead one). DcsPanel sends
/// COLMOD/MADCTL after the table (command set 1, valid in every mode) and its own SLPOUT, so
/// the tables' trailing SLPOUT (and the ST77922's TEON) are dropped.
